"""
Built-in functions are functions that are pre-defined in Python and can be used without the need for importing any module. They provide a wide range of functionalities, such as performing mathematical operations, manipulating data structures, and handling input/output operations. Some commonly used built-in functions include:
- `len()`: Returns the length of an object.
- `max()`: Returns the largest item in an iterable or the largest of two or more arguments.
- `min()`: Returns the smallest item in an iterable or the smallest of two or more arguments.
- `sum()`: Sums the items of an iterable.
- `abs()`: Returns the absolute value of a number.
- `type()`: Returns the type of an object.
"""

name = "Bishal Rijal"
print(len(name))


numbers = [1, 2, 3, 4, 5]
print(max(numbers))
print(min(numbers))
print(sum(numbers))


num = -34
print(abs(num))

print(type(name))
